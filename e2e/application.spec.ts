test('añadir pendiente conserva estado al navegar y anuncia éxito en listado', async ({ page }) => {
  const calls = await mockApi(page)
  let release!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  let posts = 0
  await page.route('https://itx-frontend-test.onrender.com/api/cart', async route => {
    if (route.request().method() === 'OPTIONS') return route.fulfill({ status: 204 })
    posts++
    await pending
    await route.fulfill({ json: { count: 7 } })
  })
  await page.goto(`/product/${details[0].id}`)
  await page.getByLabel('Almacenamiento', { exact: true }).selectOption('2000')
  await page.getByRole('button', { name: 'Añadir', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Añadiendo…' })).toBeDisabled()
  await expect(counter(page, 0)).toBeVisible()
  await page.getByRole('navigation').getByRole('link', { name: 'Listado' }).click()
  release()
  await expect(counter(page, 7)).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'Producto añadido' })).toBeVisible()
  await checkAccessibility(page)
  expect(posts).toBe(1)
  expect(calls.cart).toHaveLength(0)
  await page.reload()
  await expect(counter(page, 7)).toBeVisible()
  expect(posts).toBe(1)
})
