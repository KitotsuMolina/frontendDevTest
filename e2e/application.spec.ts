import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { details, mockApi, products } from './api'

const searchName = 'Buscar por marca o modelo'
const counter = (page: Page, count: number) => page.getByLabel(`Cesta: ${count} productos`)
async function checkAccessibility(page: Page) {
  // axe calcula colores renderizados; esperar las entradas evita medir un fundido intermedio.
  for (const element of await page.locator('.catalog-page, .catalog-results, .detail-enter').all()) {
    await expect(element).toHaveCSS('opacity', '1')
  }
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
  expect(result.violations).toEqual([])
}
async function checkOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
}

test('listado → búsqueda → detalle → selección → cesta → navegación → recarga', async ({ page }) => {
  const calls = await mockApi(page)
  await page.goto('/')
  await expect(page.getByRole('link', { name: 'Acer Iconia Talk S', exact: true })).toBeVisible()
  await page.evaluate(() => Reflect.set(window, 'documentMarker', 'same-document'))
  await expect(page.getByRole('list', { name: 'Productos' }).getByRole('link')).toHaveCount(products.length)
  await expect(page.getByText('Precio no disponible', { exact: true })).toBeVisible()
  const search = page.getByRole('searchbox', { name: searchName })
  await search.fill('  aCeR  ')
  await expect(page.getByRole('list', { name: 'Productos' }).getByRole('link')).toHaveCount(3)
  await search.fill(' TALK ')
  await expect(page.getByRole('list', { name: 'Productos' }).getByRole('link')).toHaveCount(1)
  expect(calls.list).toBe(1)
  await page.getByRole('link', { name: 'Acer Iconia Talk S', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Iconia Talk S' })).toBeVisible()
  expect(await page.evaluate(() => Reflect.get(window, 'documentMarker'))).toBe('same-document')
  await expect(page.getByRole('main')).toBeFocused()
  await expect(page.getByRole('navigation').getByText('Acer Iconia Talk S')).toHaveAttribute('aria-current', 'page')
  await expect(page.getByLabel('Color', { exact: true })).toHaveValue('1000')
  await expect(page.getByRole('button', { name: 'Añadir', exact: true })).toBeDisabled()
  await page.getByLabel('Almacenamiento', { exact: true }).selectOption('2001')
  await page.getByRole('button', { name: 'Añadir', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Producto añadido' })).toBeVisible()
  await expect(counter(page, 3)).toBeVisible()
  expect(calls.cart).toEqual([{ id: details[0].id, colorCode: 1000, storageCode: 2001 }])
  await page.getByRole('navigation').getByRole('link', { name: 'Listado' }).click()
  await expect(counter(page, 3)).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: 'Acer Iconia Talk S', exact: true })).toBeVisible()
  await expect(counter(page, 3)).toBeVisible()
  expect(calls.list).toBe(1)
  expect(calls.cart).toHaveLength(1)
})

test('error de cesta conserva contador y permite únicamente reintento manual', async ({ page }) => {
  const calls = await mockApi(page, { cartError: true })
  await page.goto(`/product/${details[1].id}`)
  await expect(page.getByRole('heading', { name: 'Liquid Z6 Plus' })).toBeVisible()
  await expect(page.getByLabel('Almacenamiento', { exact: true })).toHaveValue('2000')
  await expect(page.getByRole('button', { name: 'Añadir', exact: true })).toBeDisabled()
  await page.getByLabel('Color', { exact: true }).selectOption('1001')
  await page.getByRole('button', { name: 'Añadir', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('El contador no ha cambiado')
  await expect(counter(page, 0)).toBeVisible()
  await checkAccessibility(page)
  expect(calls.cart).toHaveLength(1)
  await page.getByRole('button', { name: 'Añadir', exact: true }).click()
  await expect(counter(page, 3)).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(calls.cart).toEqual(Array(2).fill({ id: details[1].id, colorCode: 1001, storageCode: 2000 }))
})

test('preview admite URL de detalle directa, recarga, historial y expiración exacta', async ({ page }) => {
  const calls = await mockApi(page)
  const response = await page.goto(`/product/${details[0].id}`)
  expect(response?.status()).toBe(200)
  await expect(page.getByRole('heading', { name: 'Iconia Talk S' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Iconia Talk S' })).toBeVisible()
  expect(calls.detail).toBe(1)
  await page.getByRole('navigation').getByRole('link', { name: 'Listado' }).click()
  await page.getByRole('link', { name: 'Acer Liquid Z6 Plus', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Liquid Z6 Plus' })).toBeVisible()
  await expect(page.getByLabel('Color', { exact: true })).toHaveValue('')
  await page.goBack()
  await expect(page.getByRole('searchbox', { name: searchName })).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('heading', { name: 'Liquid Z6 Plus' })).toBeVisible()
  expect(calls.detail).toBe(2)
  // Hora controlada: justo expiresAt es inválido. No se espera una hora real.
  const expiresAt = await page.evaluate(id => JSON.parse(localStorage.getItem(`nunegal:query:v1:product:${id}`)!).expiresAt as number, details[1].id)
  await page.addInitScript(timestamp => { Date.now = () => timestamp }, expiresAt)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Liquid Z6 Plus' })).toBeVisible()
  expect(calls.detail).toBe(3)
  expect(calls.list).toBe(1)
})

test('estructura adaptable, controles, mensajes y contraste en ambas vistas', async ({ page }, testInfo) => {
  await mockApi(page)
  await page.goto('/')
  await expect(page.locator('.catalog-results')).toHaveCSS('opacity', '1')
  const columns = await page.locator('ul.product-grid').evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)
  expect(columns).toBe(testInfo.project.name === 'desktop' ? 4 : testInfo.project.name === 'tablet' ? 2 : 1)
  await checkOverflow(page)
  await checkAccessibility(page)
  await page.screenshot({ path: testInfo.outputPath('listado.png'), fullPage: true, animations: 'disabled' })
  await page.getByRole('link', { name: 'Acer Iconia Talk S', exact: true }).click()
  await expect(page.locator('.detail-enter')).toHaveCSS('opacity', '1')
  const image = await page.locator('.detail-image').boundingBox()
  const description = await page.locator('.detail-description').boundingBox()
  expect(image).not.toBeNull()
  expect(description).not.toBeNull()
  if (testInfo.project.name === 'desktop') expect(description!.x).toBeGreaterThan(image!.x + image!.width)
  else expect(description!.y).toBeGreaterThan(image!.y + image!.height)
  const tab = await page.locator('.detail-back-tab').boundingBox()
  expect(image!.y).toBeGreaterThan(tab!.y + tab!.height)
  await checkOverflow(page)
  await checkAccessibility(page)
  await page.screenshot({ path: testInfo.outputPath('detalle.png'), fullPage: true, animations: 'disabled' })
  await page.getByLabel('Almacenamiento', { exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('selector.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
})

