test('esqueletos anuncian carga sin movimiento y fallo del listado admite reintento', async ({ page }) => {
  let release!: () => void
  const delayedList = new Promise<void>(resolve => { release = resolve })
  const calls = await mockApi(page, { delayedList, listError: true })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByRole('status', { name: 'Cargando productos' })).toHaveAttribute('aria-busy', 'true')
  expect(await page.locator('.skeleton').first().evaluate(element => getComputedStyle(element, '::after').animationName)).toBe('none')
  await checkAccessibility(page)
  release()
  await expect(page.getByRole('alert')).toContainText('No se pudieron cargar')
  await page.getByRole('button', { name: 'Reintentar' }).click()
  await expect(page.getByRole('link', { name: 'Acer Iconia Talk S', exact: true })).toBeVisible()
  expect(calls.list).toBe(2)
  await page.getByRole('searchbox', { name: searchName }).fill('sin coincidencias')
  await expect(page.getByText('No se encontraron productos. Prueba con otra marca o modelo.')).toBeVisible()
  expect(calls.list).toBe(2)
})

